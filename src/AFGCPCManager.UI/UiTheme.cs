public sealed class AfgcTabControl : TabControl
{
    private int _metricsDpi = 96;

    public AfgcTabControl()
    {
        DrawMode = TabDrawMode.OwnerDrawFixed;
        SizeMode = TabSizeMode.Fixed;
        ItemSize = new Size(140, 38);
        Padding = new Point(16, 5);
        SetStyle(ControlStyles.OptimizedDoubleBuffer, true);
        HandleCreated += (_, _) => QueueDpiMetrics();
        DpiChangedAfterParent += (_, _) => ApplyDpiMetrics();
    }

    private void QueueDpiMetrics()
    {
        if (_metricsDpi == DeviceDpi || !IsHandleCreated) return;
        BeginInvoke(() =>
        {
            if (!IsDisposed) ApplyDpiMetrics();
        });
    }

    private void ApplyDpiMetrics()
    {
        _metricsDpi = DeviceDpi;
        ItemSize = new Size(UiTheme.Scale(this, 140), UiTheme.Scale(this, 38));
        Padding = new Point(UiTheme.Scale(this, 16), UiTheme.Scale(this, 5));
        Invalidate();
    }

    protected override void OnDrawItem(DrawItemEventArgs e)
    {
        bool selected = e.Index == SelectedIndex;
        Rectangle bounds = GetTabRect(e.Index);
        Color background = selected ? UiTheme.PrimarySoft : UiTheme.Surface;
        Color foreground = selected ? UiTheme.Primary : UiTheme.TextMuted;
        using var brush = new SolidBrush(background);
        e.Graphics.FillRectangle(brush, bounds);
        TextRenderer.DrawText(e.Graphics, TabPages[e.Index].Text, UiTheme.BodyFont, bounds,
            foreground, TextFormatFlags.HorizontalCenter | TextFormatFlags.VerticalCenter |
            TextFormatFlags.NoPrefix);
        if (selected)
        {
            using var pen = new Pen(UiTheme.Primary, 2);
            e.Graphics.DrawLine(pen, bounds.Left + 10, bounds.Bottom - 1,
                bounds.Right - 10, bounds.Bottom - 1);
        }
    }
}

public sealed class AfgcStatusBanner : Panel
{
    private readonly Label _message = new()
    {
        Dock = DockStyle.Fill,
        AutoEllipsis = true,
        TextAlign = ContentAlignment.MiddleLeft,
        Padding = new Padding(0),
        Font = UiTheme.BodyFont
    };
    private readonly StatusDot _dot = new();

    public AfgcStatusBanner()
    {
        Height = 54;
        Dock = DockStyle.Bottom;
        BackColor = UiTheme.Surface;
        Padding = new Padding(28, 0, 28, 0);
        Controls.Add(_message);
        Controls.Add(_dot);
        SetStyle(ControlStyles.AllPaintingInWmPaint | ControlStyles.OptimizedDoubleBuffer |
                 ControlStyles.ResizeRedraw | ControlStyles.UserPaint, true);
    }

    public void SetMessage(string value)
    {
        _message.Text = value;
        Color tone = DetermineTone(value);
        _message.ForeColor = tone == UiTheme.Danger ? UiTheme.Danger : UiTheme.TextMuted;
        _dot.SetTone(tone);
    }

    protected override void OnPaint(PaintEventArgs e)
    {
        using var pen = new Pen(UiTheme.Border);
        e.Graphics.DrawLine(pen, 0, 0, Width, 0);
    }

    private static Color DetermineTone(string value)
    {
        if (value.Contains("Running", StringComparison.OrdinalIgnoreCase)) return UiTheme.Success;
        if (value.Contains("failed", StringComparison.OrdinalIgnoreCase)
            || value.Contains("error", StringComparison.OrdinalIgnoreCase)
            || value.Contains("stopped", StringComparison.OrdinalIgnoreCase)) return UiTheme.Danger;
        if (value.Contains("required", StringComparison.OrdinalIgnoreCase)
            || value.Contains("unavailable", StringComparison.OrdinalIgnoreCase)
            || value.Contains("withheld", StringComparison.OrdinalIgnoreCase)) return UiTheme.Warning;
        return UiTheme.Primary;
    }

    private sealed class StatusDot : Panel
    {
        private Color _toneColor = UiTheme.Primary;
        public void SetTone(Color value) { _toneColor = value; Invalidate(); }

        public StatusDot()
        {
            Size = new Size(18, 18);
            Dock = DockStyle.Left;
            Margin = Padding.Empty;
            Padding = new Padding(0);
            BackColor = UiTheme.Surface;
        }

        protected override void OnPaint(PaintEventArgs e)
        {
            e.Graphics.SmoothingMode = SmoothingMode.AntiAlias;
            using var brush = new SolidBrush(_toneColor);
            e.Graphics.FillEllipse(brush,
                UiTheme.Scale(this, 3), UiTheme.Scale(this, 6),
                UiTheme.Scale(this, 7), UiTheme.Scale(this, 7));
        }
    }
}

public enum AfgcCalloutTone { Info, Warning, Danger }

public sealed class AfgcCallout : Panel
{
    private readonly Label _label = new()
    {
        Dock = DockStyle.Fill,
        AutoSize = false,
        Padding = new Padding(14, 10, 14, 10),
        Font = UiTheme.BodyFont
    };
    private AfgcCalloutTone _tone;

    [DefaultValue(AfgcCalloutTone.Info)]
    public AfgcCalloutTone Tone
    {
        get => _tone;
        set { _tone = value; ApplyTone(); }
    }

    [AllowNull]
    public override string Text
    {
        get => _label.Text;
        set { _label.Text = value ?? string.Empty; base.Text = value ?? string.Empty; }
    }

    public AfgcCallout(string text, AfgcCalloutTone tone = AfgcCalloutTone.Info)
    {
        Height = 56;
        Margin = Padding.Empty;
        Padding = new Padding(3, 0, 0, 0);
        Controls.Add(_label);
        HandleCreated += (_, _) => ApplyDpiMetrics();
        DpiChangedAfterParent += (_, _) => ApplyDpiMetrics();
        _tone = tone;
        Text = text;
        ApplyTone();
    }

    private void ApplyDpiMetrics()
    {
        Padding = new Padding(UiTheme.Scale(this, 3), 0, 0, 0);
        int horizontal = UiTheme.Scale(this, 14);
        int vertical = UiTheme.Scale(this, 10);
        _label.Padding = new Padding(horizontal, vertical, horizontal, vertical);
    }

    private void ApplyTone()
    {
        (Color accent, Color background) = _tone switch
        {
            AfgcCalloutTone.Warning => (UiTheme.Warning, UiTheme.WarningSoft),
            AfgcCalloutTone.Danger => (UiTheme.Danger, UiTheme.DangerSoft),
            _ => (UiTheme.Primary, UiTheme.PrimarySoft)
        };
        BackColor = accent;
        _label.BackColor = background;
        _label.ForeColor = _tone == AfgcCalloutTone.Danger ? UiTheme.Danger : UiTheme.Text;
    }
}
